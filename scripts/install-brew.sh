#!/bin/bash
set -euo pipefail
PROJECT_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$PROJECT_ROOT"
command -v brew >/dev/null || { echo "Install Homebrew first: https://brew.sh" >&2; exit 1; }
# Build for this Mac, then let Homebrew manage installation and removal.
./scripts/build-app.sh
VERSION=$(/usr/libexec/PlistBuddy -c 'Print CFBundleShortVersionString' Resources/Info.plist)
ARCHIVE="$PROJECT_ROOT/dist/RestFlow-$VERSION.app.zip"
ditto -c -k --sequesterRsrc --keepParent dist/RestFlow.app "$ARCHIVE"
if ! brew tap | /usr/bin/grep -qx 'restflow/local'; then
    brew tap-new --no-git restflow/local
fi
TAP_ROOT="$(brew --repository restflow/local)"
mkdir -p "$TAP_ROOT/Casks"
# Use URI escaping and a checksum; paths with spaces work as well.
python3 - "$ARCHIVE" "$TAP_ROOT/Casks/restflow.rb" "$PROJECT_ROOT" "$VERSION" <<'PY'
import hashlib, json, pathlib, sys
archive, target, root, version = sys.argv[1:]
source = pathlib.Path(archive)
quote = json.dumps
pathlib.Path(target).write_text(f'''# Generated by RestFlow scripts/install-brew.sh. Local build, no public tap required.
cask "restflow" do
  version {quote(version)}
  sha256 "{hashlib.sha256(source.read_bytes()).hexdigest()}"

  url {quote(source.as_uri())}
  name "RestFlow"
  desc "Menu bar break timer"
  homepage {quote(pathlib.Path(root).as_uri())}

  depends_on macos: :ventura

  app "RestFlow.app"
end
''')
PY
if brew list --cask restflow/local/restflow >/dev/null 2>&1; then
    brew reinstall --cask --appdir=/Applications restflow/local/restflow
else
    brew install --cask --appdir=/Applications restflow/local/restflow
fi

# Homebrew 7 quarantines even file:// archives and removed --no-quarantine.
# This is our own local build: verify all bundle bytes before clearing only
# this copy's download marker. No global Gatekeeper settings are changed.
python3 - "$PROJECT_ROOT/dist/RestFlow.app" /Applications/RestFlow.app <<'PYCOMPARE'
import hashlib, os, pathlib, sys

def manifest(root):
    result = {}
    base = pathlib.Path(root)
    for folder, dirs, files in os.walk(base, followlinks=False):
        for name in dirs + files:
            path = pathlib.Path(folder) / name
            key = str(path.relative_to(base))
            if path.is_symlink():
                result[key] = ("link", os.readlink(path))
            elif path.is_file():
                result[key] = ("file", hashlib.sha256(path.read_bytes()).hexdigest())
            else:
                result[key] = ("directory",)
    return result

if manifest(sys.argv[1]) != manifest(sys.argv[2]):
    raise SystemExit("Installed app differs from the local build; leaving its attributes untouched.")
PYCOMPARE
codesign --verify --deep --strict /Applications/RestFlow.app
/usr/bin/xattr -dr com.apple.quarantine /Applications/RestFlow.app
